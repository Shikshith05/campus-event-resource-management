-- Non-destructive upgrade for an existing CERMS database.
-- Run as the database owner after the existing schema and RBAC roles exist:
--   psql -v ON_ERROR_STOP=1 -d cerms -f db/sql/migrations/001_venue_ranges_and_approver_assignments.sql
-- Then install the updated SQL routines with procedures.sql and workflow.sql.

BEGIN;

ALTER TABLE venue ADD COLUMN IF NOT EXISTS min_capacity INT;
ALTER TABLE venue ADD COLUMN IF NOT EXISTS max_capacity INT;
ALTER TABLE venue ADD COLUMN IF NOT EXISTS venue_type_confirmed BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE venue ALTER COLUMN capacity DROP NOT NULL;

UPDATE venue
SET min_capacity = capacity,
    max_capacity = capacity
WHERE min_capacity IS NULL
  AND max_capacity IS NULL
  AND capacity IS NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'chk_venue_capacity_range'
          AND conrelid = 'venue'::regclass
    ) THEN
        ALTER TABLE venue ADD CONSTRAINT chk_venue_capacity_range CHECK (
            (min_capacity IS NULL AND max_capacity IS NULL) OR
            (min_capacity > 0 AND max_capacity >= min_capacity)
        );
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS workflow_approver_assignment (
    assignment_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INT NOT NULL REFERENCES app_user (user_id) ON DELETE RESTRICT,
    approver_role  VARCHAR(40) NOT NULL
                   CHECK (approver_role IN ('CLUB_COORDINATOR', 'HOD',
                                            'DEAN_OF_STUDENT_AFFAIRS', 'VICE_CHANCELLOR')),
    department_id  INT REFERENCES department (department_id) ON DELETE CASCADE,
    club_id        INT REFERENCES club (club_id) ON DELETE CASCADE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_workflow_assignment_scope CHECK (
        (approver_role = 'CLUB_COORDINATOR') OR
        (approver_role = 'HOD' AND department_id IS NOT NULL AND club_id IS NULL) OR
        (approver_role IN ('DEAN_OF_STUDENT_AFFAIRS', 'VICE_CHANCELLOR')
            AND department_id IS NULL AND club_id IS NULL)
    ),
    CONSTRAINT chk_workflow_assignment_one_scope CHECK (
        department_id IS NULL OR club_id IS NULL
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_workflow_club_coordinator_club
    ON workflow_approver_assignment (club_id)
    WHERE approver_role = 'CLUB_COORDINATOR' AND club_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_workflow_club_coordinator_department
    ON workflow_approver_assignment (department_id)
    WHERE approver_role = 'CLUB_COORDINATOR' AND department_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_workflow_club_coordinator_global
    ON workflow_approver_assignment (approver_role)
    WHERE approver_role = 'CLUB_COORDINATOR' AND department_id IS NULL AND club_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_workflow_hod_department
    ON workflow_approver_assignment (department_id)
    WHERE approver_role = 'HOD';
CREATE UNIQUE INDEX IF NOT EXISTS uq_workflow_dean_global
    ON workflow_approver_assignment (approver_role)
    WHERE approver_role = 'DEAN_OF_STUDENT_AFFAIRS';
CREATE UNIQUE INDEX IF NOT EXISTS uq_workflow_vc_global
    ON workflow_approver_assignment (approver_role)
    WHERE approver_role = 'VICE_CHANCELLOR';

INSERT INTO role (role_name, hierarchy_level, description)
VALUES ('WORKFLOW_APPROVER', 3,
        'Can act only on workflow stages assigned to this account')
ON CONFLICT (role_name) DO UPDATE
SET description = EXCLUDED.description;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'cerms_workflow_approver') THEN
        CREATE ROLE cerms_workflow_approver NOLOGIN;
    END IF;
END $$;

GRANT cerms_workflow_approver TO cerms_app;
GRANT USAGE ON SCHEMA public TO cerms_workflow_approver;
GRANT SELECT (status) ON event TO cerms_workflow_approver;

COMMIT;
