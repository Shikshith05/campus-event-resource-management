-- =====================================================================
-- CERMS - Campus Event and Resource Management System
-- PostgreSQL schema (DDL only)
--
-- Core relational design: tables, keys and constraints.
--
-- Run (database must already exist):
--   psql -v ON_ERROR_STOP=1 -d cerms -f db/sql/schema.sql
--
-- WARNING: this script DROPS and recreates every CERMS table.
-- =====================================================================

-- btree_gist lets a single GiST index combine "=" on venue_id with
-- "&&" (overlaps) on a time range. It is needed by the no-double-booking
-- constraint on the booking table. It ships with standard PostgreSQL.
CREATE EXTENSION IF NOT EXISTS btree_gist;

DROP TABLE IF EXISTS
    booking_conflict_log, booking_resource, booking, event,
    event_venue_preference, guest_lecture_details, resource, venue,
    club_member, club, app_user,
    role, department
CASCADE;


-- ---------------------------------------------------------------------
-- department: academic departments (CSE, ECE, ...)
-- ---------------------------------------------------------------------
CREATE TABLE department (
    department_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(10)  NOT NULL UNIQUE,     -- short code, e.g. 'CSE'
    name           VARCHAR(100) NOT NULL UNIQUE
);


-- ---------------------------------------------------------------------
-- role: the five system roles used for access control
-- ---------------------------------------------------------------------
CREATE TABLE role (
    role_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name        VARCHAR(30) NOT NULL UNIQUE,    -- 'STUDENT', 'HOD', ...
    -- Higher level = more authority. Used for access checks and as the
    -- "requester role" factor of the priority score. Not UNIQUE, so two
    -- roles may share a level (e.g. a future DEAN next to ADMIN).
    hierarchy_level  SMALLINT    NOT NULL CHECK (hierarchy_level > 0),
    description      VARCHAR(200)
);


-- ---------------------------------------------------------------------
-- app_user: every person who logs in. Named app_user because USER is a
-- reserved word in PostgreSQL.
-- ---------------------------------------------------------------------
CREATE TABLE app_user (
    user_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    university_id  VARCHAR(20)  NOT NULL UNIQUE,     -- SRN for students, employee ID for staff
    full_name      VARCHAR(100) NOT NULL,
    email          VARCHAR(120) NOT NULL UNIQUE,
    password_hash  TEXT         NOT NULL,            -- bcrypt hash, never the plain password
    role_id        INT          NOT NULL
                   REFERENCES role (role_id) ON DELETE RESTRICT,
    -- NULL only for central staff (e.g. admin office) with no department.
    department_id  INT
                   REFERENCES department (department_id) ON DELETE RESTRICT,
    -- Users are deactivated, never deleted, so old events/bookings that
    -- point to them stay valid. That is why FKs to app_user use RESTRICT.
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- Emails are stored in lowercase so UNIQUE cannot be bypassed by
    -- changing letter case (A@x.com vs a@x.com).
    CONSTRAINT chk_user_email CHECK (email LIKE '_%@_%' AND email = lower(email))
);


-- ---------------------------------------------------------------------
-- club: student clubs, each with one faculty advisor
-- ---------------------------------------------------------------------
CREATE TABLE club (
    club_id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100) NOT NULL UNIQUE,
    description         TEXT,
    -- NULL = campus-wide club. If a department is removed, its clubs
    -- simply become campus-wide (SET NULL).
    department_id       INT
                        REFERENCES department (department_id) ON DELETE SET NULL,
    faculty_advisor_id  INT NOT NULL
                        REFERENCES app_user (user_id) ON DELETE RESTRICT,
    is_active           BOOLEAN NOT NULL DEFAULT TRUE
);


-- ---------------------------------------------------------------------
-- club_member: which users belong to which clubs (M:N bridge table)
-- ---------------------------------------------------------------------
CREATE TABLE club_member (
    club_id        INT NOT NULL
                   REFERENCES club (club_id) ON DELETE CASCADE,
    user_id        INT NOT NULL
                   REFERENCES app_user (user_id) ON DELETE CASCADE,
    -- Position inside THIS club. The system role in app_user says what a
    -- user may do in the app; this says which club they lead.
    club_position  VARCHAR(20) NOT NULL DEFAULT 'MEMBER'
                   CHECK (club_position IN ('MEMBER', 'COORDINATOR')),
    joined_on      DATE NOT NULL DEFAULT CURRENT_DATE,

    PRIMARY KEY (club_id, user_id)                   -- a user joins a club only once
);


-- ---------------------------------------------------------------------
-- venue: bookable spaces (auditoriums, seminar halls, classrooms, ...)
-- ---------------------------------------------------------------------
CREATE TABLE venue (
    venue_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL UNIQUE,
    venue_type     VARCHAR(20)  NOT NULL
                   CHECK (venue_type IN ('AUDITORIUM', 'SEMINAR_HALL', 'CLASSROOM',
                                         'LAB', 'OPEN_AIR', 'OTHER')),
    building       VARCHAR(100),
    capacity       INT NOT NULL CHECK (capacity > 0),
    -- Department that manages the venue; NULL = managed centrally by admin.
    department_id  INT
                   REFERENCES department (department_id) ON DELETE SET NULL,
    -- Venues are retired (is_active = FALSE), not deleted, because
    -- bookings reference them.
    is_active      BOOLEAN NOT NULL DEFAULT TRUE
);


-- ---------------------------------------------------------------------
-- resource: shared equipment pool (projectors, mics, chairs, ...)
-- ---------------------------------------------------------------------
CREATE TABLE resource (
    resource_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL UNIQUE,
    resource_type   VARCHAR(20)  NOT NULL
                    CHECK (resource_type IN ('AV', 'FURNITURE', 'POWER', 'DECOR', 'OTHER')),
    -- 0 is allowed: the item is tracked but none are usable right now.
    total_quantity  INT NOT NULL CHECK (total_quantity >= 0),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE
);


-- ---------------------------------------------------------------------
-- event: one event request (what, who, how many people)
-- ---------------------------------------------------------------------
CREATE TABLE event (
    event_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title              VARCHAR(150) NOT NULL,
    description        TEXT,
    -- category drives the priority score (ACADEMIC > DEPARTMENT > CLUB > PERSONAL).
    category           VARCHAR(20) NOT NULL
                       CHECK (category IN ('ACADEMIC', 'DEPARTMENT', 'CLUB', 'PERSONAL')),
    -- event_type (plus category and department) picks the approval
    -- workflow template in MongoDB.
    event_type         VARCHAR(20) NOT NULL
                       CHECK (event_type IN ('GUEST_LECTURE', 'WORKSHOP', 'SEMINAR', 'TECH_FEST',
                                             'CULTURAL', 'CLUB_MEET', 'ORIENTATION',
                                             'COMPETITION', 'SPORTS', 'OTHER')),
    organizer_id       INT NOT NULL                  -- the requester
                       REFERENCES app_user (user_id) ON DELETE RESTRICT,
    department_id      INT
                       REFERENCES department (department_id) ON DELETE RESTRICT,
    club_id            INT
                       REFERENCES club (club_id) ON DELETE RESTRICT,
    expected_footfall  INT NOT NULL CHECK (expected_footfall > 0),
    -- Final approval outcome. Stage-by-stage progress lives in MongoDB
    -- (workflow_instances).
    status             VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
                       CHECK (status IN ('DRAFT', 'PENDING_APPROVAL', 'APPROVED',
                                         'REJECTED', 'CANCELLED')),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- A CLUB event must say which club; any other category must not.
    CONSTRAINT chk_event_club CHECK (
        (category = 'CLUB' AND club_id IS NOT NULL) OR
        (category <> 'CLUB' AND club_id IS NULL)
    ),
    -- Every non-personal event belongs to a department, because that
    -- department's HOD is part of its approval chain.
    CONSTRAINT chk_event_department CHECK (
        category = 'PERSONAL' OR department_id IS NOT NULL
    )
);


-- ---------------------------------------------------------------------
-- event_venue_preference: ranked venue choices for an event request.
-- The booking table records the venue actually assigned.
-- ---------------------------------------------------------------------
CREATE TABLE event_venue_preference (
    event_id         INT NOT NULL
                     REFERENCES event (event_id) ON DELETE CASCADE,
    venue_id         INT NOT NULL
                     REFERENCES venue (venue_id) ON DELETE RESTRICT,
    preference_order SMALLINT NOT NULL CHECK (preference_order > 0),

    PRIMARY KEY (event_id, venue_id),
    CONSTRAINT uq_event_venue_preference_order
        UNIQUE (event_id, preference_order)
);


-- ---------------------------------------------------------------------
-- guest_lecture_details: fields required by the guest-lecture workflow.
-- ---------------------------------------------------------------------
CREATE TABLE guest_lecture_details (
    event_id          INT PRIMARY KEY
                      REFERENCES event (event_id) ON DELETE CASCADE,
    guest_name        VARCHAR(150) NOT NULL,
    guest_affiliation VARCHAR(200) NOT NULL,
    talk_topic        VARCHAR(250) NOT NULL
);


-- ---------------------------------------------------------------------
-- booking: one venue for one time slot, requested for an event.
-- An event can have several bookings (multi-day event, or a new booking
-- in an alternate venue after losing a clash).
-- ---------------------------------------------------------------------
CREATE TABLE booking (
    booking_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Bookings are part of their event: deleting a (draft) event removes them.
    event_id      INT NOT NULL
                  REFERENCES event (event_id) ON DELETE CASCADE,
    venue_id      INT NOT NULL
                  REFERENCES venue (venue_id) ON DELETE RESTRICT,
    start_time    TIMESTAMPTZ NOT NULL,
    end_time      TIMESTAMPTZ NOT NULL,
    -- CANCELLED = withdrawn by the requester; NO_SHOW = confirmed but
    -- never used. Both count against the requester's priority score.
    -- REJECTED = lost a clash or denied by an approver (no penalty).
    status        VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                  CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED',
                                    'CANCELLED', 'COMPLETED', 'NO_SHOW')),
    requested_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT chk_booking_time CHECK (end_time > start_time),
    -- A slot can only be requested in advance. (start_time - requested_at)
    -- is the "booking lead time" factor of the priority score.
    CONSTRAINT chk_booking_lead_time CHECK (start_time > requested_at),
    -- No double-booking: two CONFIRMED bookings of the same venue can
    -- never overlap in time. PENDING bookings may overlap; that is the
    -- clash the priority logic resolves. '[)' includes the start and
    -- excludes the end, so 10:00-12:00 and 12:00-14:00 do not clash.
    CONSTRAINT excl_booking_no_overlap EXCLUDE USING gist (
        venue_id WITH =,
        tstzrange(start_time, end_time, '[)') WITH &&
    ) WHERE (status = 'CONFIRMED')
);


-- ---------------------------------------------------------------------
-- booking_resource: equipment requested for a booking (M:N bridge
-- between booking and resource, with a quantity)
-- ---------------------------------------------------------------------
CREATE TABLE booking_resource (
    booking_id   INT NOT NULL
                 REFERENCES booking (booking_id) ON DELETE CASCADE,
    resource_id  INT NOT NULL
                 REFERENCES resource (resource_id) ON DELETE RESTRICT,
    quantity     INT NOT NULL CHECK (quantity > 0),

    PRIMARY KEY (booking_id, resource_id)            -- one line per resource per booking
    -- "quantity <= what is free in that slot" depends on other rows, so it
    -- cannot be a CHECK. It will be enforced by a trigger/function later.
);


-- ---------------------------------------------------------------------
-- booking_conflict_log: audit trail of every priority decision, i.e.
-- which of two clashing bookings won and with what scores.
-- ---------------------------------------------------------------------
CREATE TABLE booking_conflict_log (
    conflict_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- RESTRICT keeps the audit trail safe: a booking (or its event) that
    -- took part in a priority decision cannot be deleted, only cancelled.
    winning_booking_id  INT NOT NULL
                        REFERENCES booking (booking_id) ON DELETE RESTRICT,
    losing_booking_id   INT NOT NULL
                        REFERENCES booking (booking_id) ON DELETE RESTRICT,
    -- Scores are a snapshot at decision time (cancellation counts and
    -- weights change later), so they are stored, not recomputed.
    winner_score        NUMERIC(6,2) NOT NULL,
    loser_score         NUMERIC(6,2) NOT NULL,
    reason              TEXT,
    -- NULL = decided automatically by the system; otherwise the admin
    -- who manually overrode the decision.
    decided_by          INT
                        REFERENCES app_user (user_id) ON DELETE RESTRICT,
    decided_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT chk_conflict_two_bookings CHECK (winning_booking_id <> losing_booking_id),
    CONSTRAINT uq_conflict_pair UNIQUE (winning_booking_id, losing_booking_id),
    -- An automatic decision must follow the scores. Only a manual
    -- override (decided_by is set) may pick the lower-scoring booking.
    CONSTRAINT chk_conflict_auto_follows_score CHECK (
        decided_by IS NOT NULL OR winner_score >= loser_score
    )
);


-- ---------------------------------------------------------------------
-- Indexes. PostgreSQL indexes primary keys and UNIQUE columns itself,
-- but NOT foreign keys. These cover the most frequent lookups.
-- ---------------------------------------------------------------------
CREATE INDEX idx_booking_venue_time ON booking (venue_id, start_time);  -- availability search
CREATE INDEX idx_booking_event      ON booking (event_id);              -- bookings of an event
CREATE INDEX idx_event_organizer    ON event (organizer_id);            -- a requester's history (cancellations, no-shows)
